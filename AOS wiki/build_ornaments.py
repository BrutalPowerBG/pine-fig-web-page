#!/usr/bin/env python3
"""Embed the ornament PNGs in css/ornaments.css.

Chrome refuses image-file masks when index.html is opened straight from the
folder (file://), so each ornament is inlined as a --orn-<name> data URI.
Run after adding or changing a PNG in images/ornaments/:

    python build_ornaments.py
"""
from __future__ import annotations

import base64
import os

ROOT = os.path.dirname(os.path.abspath(__file__))
SOURCE = os.path.join(ROOT, "images", "ornaments")
TARGET = os.path.join(ROOT, "css", "ornaments.css")

# Only the ornaments the CSS uses; the folder holds the full cut-out set from images/pattern.jpg.
USED = [
    "leaf", "divider", "sweep", "rosette", "pendant", "shell", "corner-swirl", "vine-left", "vine-right",
    "plume", "flourish", "feather", "sprig", "swirl",
]


def main() -> None:
    lines = [
        "/* Generated by build_ornaments.py from images/ornaments/*.png. Do not edit by hand. */",
        ":root {",
    ]
    for name in USED:
        with open(os.path.join(SOURCE, name + ".png"), "rb") as handle:
            data = base64.b64encode(handle.read()).decode("ascii")
        lines.append('  --orn-%s: url("data:image/png;base64,%s");' % (name, data))
    lines.append("}")
    with open(TARGET, "w", encoding="utf-8", newline="\n") as handle:
        handle.write("\n".join(lines) + "\n")
    print("Wrote %s (%d ornaments)" % (os.path.relpath(TARGET, ROOT), len(USED)))


if __name__ == "__main__":
    main()
